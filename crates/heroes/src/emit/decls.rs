/// The header every generated file opens with.
///
/// The `_Static_assert` is not decoration. The runtime is found by searching, and
/// a directory called `runtime/` is one of the commonest things in a source tree:
/// the panel's ffi-pragmatist put a decoy one in the working directory and the
/// generated C compiled with **zero warnings under `-Weverything`** and printed
/// `0x1e` where `30` was expected. With the stamp, the same C is `error: use of
/// undeclared identifier 'HERO_RUNTIME_ABI'`.
pub(super) fn prelude(w: &mut Writer, program: &Program, src: &Source) {
    w.line(&format!(
        "/* Generated by heroes {} from {}. Do not edit. */",
        crate::VERSION, src.name
    ));
    w.line("#include \"heroes_runtime.h\"");
    // `math.h` for `HUGE_VAL`, which is how an infinite `f64` literal is spelled.
    w.line("#include <math.h>");
    w.line("");
    w.line(
        "_Static_assert(HERO_RUNTIME_ABI == 7, \"heroes_runtime.h is from another compiler\");",
    );
    w.line("");
    // Every decoded string literal **an emitted function actually reads**, as a
    // static block clang lays out: refcount −1 means "never freed", so a literal
    // allocates nothing and decrefing one is a no-op. The escapes were applied once,
    // at lowering (panel 008), so this is the one place they are re-escaped for C.
    //
    // Reachability, not the whole table, and it is not tidiness: `program.strings`
    // holds every literal in the *file*, including the ones only a `test` block or an
    // `assert` message mentions — and §4.18 says ordinary builds ignore those. Emitted
    // anyway, they are `-Wunused-const-variable`, which is the same warning panel 022
    // named for an unused descriptor. Eight of them on one gallery program, on every
    // build, is how a real diagnostic gets lost in noise.
    //
    // The index is kept: `hero_str_7` stays `hero_str_7` whether or not 0..6 are
    // emitted, so the name is a function of the literal and not of what surrounds it —
    // which is what keeps `--emit-c` stable when a `test` block is added to a file.
    let live = live_strings(program);
    for (index, text) in program.strings.iter().enumerate() {
        if !live.contains(&(index as u32)) {
            continue;
        }
        w.line(&format!("HERO_STR_STATIC(hero_str_{index}, \"{}\");", escape_c(text)));
    }
    if !live.is_empty() {
        w.line("");
    }
}

/// Which string literals an emitted function reads. A walk, because the answer must
/// come from the instructions rather than from a count kept in step with them.
fn live_strings(program: &Program) -> std::collections::BTreeSet<u32> {
    let mut live = std::collections::BTreeSet::new();
    for function in &program.functions {
        if !emitted(function) {
            continue;
        }
        for block in &function.blocks {
            for inst in &block.insts {
                if let crate::ir::Op::Const(crate::ir::Const::Str(index)) = inst.op {
                    live.insert(index.0);
                }
            }
        }
    }
    live
}

/// A decoded Heroes string, as a C string literal. Octal escapes for everything
/// non-printable, because `\xNN` in C has no length limit and would swallow a
/// following hex digit.
fn escape_c(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    for byte in text.as_bytes() {
        match *byte {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            0x20..=0x7e => out.push(*byte as char),
            other => out.push_str(&format!("\\{other:03o}")),
        }
    }
    out
}

/// Whether this function reaches C at all. A `test` block does not: §4.18 says
/// ordinary builds ignore it, and `heroes test` (M6) is what enters it.
pub(super) fn emitted(function: &Function) -> bool {
    use crate::ir::FnKind;
    matches!(function.kind, FnKind::Function | FnKind::Constant)
}

pub(super) fn prototype(
    w: &mut Writer,
    function: &Function,
    ast: &Ast,
    checked: &Checked,
    names: &Names,
    module: &str,
) {
    if !emitted(function) {
        return;
    }
    let _ = ast;
    w.at_generated();
    w.line(&format!("{};", signature(function, checked, names, module)));
}

/// `int64_t h_mod_dist(int64_t h0_a, int64_t *ph1_b)`.
///
/// A mutable parameter is a **pointer** parameter — §4.8's copy-in/copy-out has no
/// other shape in C, because `Op::CopyOut` writes the *caller's* place and the
/// callee cannot otherwise reach it.
fn signature(function: &Function, checked: &Checked, names: &Names, module: &str) -> String {
    let name = mangle::function(module, &function.name);
    let result = c_result(names, checked, function.result);
    let mut params: Vec<String> = Vec::new();
    for slot in &function.params {
        params.push(param(function, checked, names, *slot));
    }
    let list = if params.is_empty() { "void".to_string() } else { params.join(", ") };
    format!("{result} {name}({list})")
}

fn param(function: &Function, checked: &Checked, names: &Names, slot: SlotId) -> String {
    let index = slot.0;
    let declared = &function.slots[index as usize];
    let ty = c_type(names, checked, declared.ty).unwrap_or_else(|| "void".to_string());
    if matches!(declared.kind, SlotKind::Param { mutable: true }) {
        format!("{ty} *{}", mangle::out_param(index, &declared.name))
    } else {
        format!("{ty} {}", mangle::slot(index, &declared.name))
    }
}

pub(super) fn definition(
    w: &mut Writer,
    program: &Program,
    function: &Function,
    ast: &Ast,
    checked: &Checked,
    names: &Names,
    src: &Source,
    module: &str,
) {
    if !emitted(function) {
        return;
    }
    w.blank();
    // The signature is pointed at the author's declaration: a clang error about a
    // parameter type has to land on the line that wrote it.
    let (line, _) = src.line_col(function.span.start);
    w.at_source(line);
    w.line(&format!("{} {{", signature(function, checked, names, module)));
    w.at_generated();
    let types = super::aggregate::Types { ast, checked, names, src };
    let live = reachable(function);
    prologue(w, function, checked, names, &live);
    w.line(&format!("    goto {};", mangle::block(0)));
    for (index, block) in function.blocks.iter().enumerate() {
        if !live[index] {
            continue;
        }
        w.line(&format!("{}:", mangle::block(index)));
        for one in &block.insts {
            inst::emit(w, program, &types, function, one, module);
        }
        term::emit(w, function, checked, &block.term);
    }
    w.at_generated();
    w.line("}");
}

/// The shim. `main` itself is mangled, so this is the only function in the unit
/// whose name C chose.
pub(super) fn shim(w: &mut Writer, function: &Function, module: &str) {
    w.blank();
    w.at_generated();
    w.line("int main(void) {");
    w.line(&format!("    {}();", mangle::function(module, &function.name)));
    // The leak gate, and it is here because AddressSanitizer is **not** one on this
    // platform: `detect_leaks is not supported`, measured, with a 999-block leak
    // exiting 0 in silence. A live-block counter asserted at exit names a count
    // instead of a stack, works everywhere, and is deterministic (panel 021 R9).
    w.line("    hero_runtime_check_leaks();");
    w.line("    return 0;");
    w.line("}");
}

/// Which blocks are reachable. A block nothing jumps to is **omitted entirely** —
/// not merely unlabelled, because C is physical and an unlabelled block would fall
/// through from the one above it.
///
/// The IR already carries the answer (`Block::preds`), so this is a lookup rather
/// than an analysis. It exists because a *correct* Heroes program produces one: an
/// `if` whose both arms `return` leaves an unreachable join block, and emitting its
/// label costs `-Wunused-label` on every build — which would then have to be
/// switched off, taking the emitter's own bugs with it.
fn reachable(function: &Function) -> Vec<bool> {
    let mut live = vec![false; function.blocks.len()];
    for (index, block) in function.blocks.iter().enumerate() {
        live[index] = index == 0 || !block.preds.is_empty();
    }
    live
}

fn prologue(w: &mut Writer, function: &Function, checked: &Checked, names: &Names, live: &[bool]) {
    for (index, slot) in function.slots.iter().enumerate() {
        // A parameter is already declared by the signature. A mutable one is
        // declared here instead: the pointer is the parameter, and the slot is the
        // local copy §4.8 says the callee works on.
        let is_param = function.params.contains(&SlotId(index as u32));
        let mutable = matches!(slot.kind, SlotKind::Param { mutable: true });
        if is_param && !mutable {
            continue;
        }
        if let Some(ty) = c_type(names, checked, slot.ty) {
            // **The one exception to "nothing is initialised here"** (panel 021 R3).
            // A refcounted slot is zeroed so that the exit sweep is unconditional:
            // `decref` of the null non-value is a no-op, and the alternative is a
            // liveness pass. clang's ARC specification licenses exactly this for
            // `__strong` locals — "may be properly initialized by filling it with
            // the representation of a null pointer" — and rustc's `ElaborateDrops`
            // does the alternative and then optimises it into the same thing.
            //
            // The cost is real and stated: `-Werror=uninitialized` stops covering
            // these, and without the zero clang would have reported a *compile
            // error*. What replaces it is `ptr == NULL` being the one non-value that
            // every runtime entry point rejects loudly, plus the verifier's own
            // store-before-load check.
            let initialiser = if is_refcounted(checked, slot.ty) { " = {0}" } else { "" };
            w.line(&format!(
                "    {ty} {}{initialiser};",
                mangle::slot(index as u32, &slot.name)
            ));
        }
    }
    for (index, ty) in function.values.iter().enumerate() {
        if is_unit(checked, *ty) || !assigned(function, live, index as u32) {
            continue;
        }
        if let Some(name) = c_type(names, checked, *ty) {
            let initialiser = if is_refcounted(checked, *ty) { " = {0}" } else { "" };
            w.line(&format!("    {name} {}{initialiser};", mangle::value(index as u32)));
        }
    }
    // Copy-in, after every declaration: §4.8's first half.
    for slot in &function.params {
        let declared = &function.slots[slot.0 as usize];
        if !matches!(declared.kind, SlotKind::Param { mutable: true }) {
            continue;
        }
        w.line(&format!(
            "    {} = *{};",
            mangle::slot(slot.0, &declared.name),
            mangle::out_param(slot.0, &declared.name)
        ));
    }
}

/// Whether any *emitted* instruction assigns this temporary. `$t0` (the unit) is
/// assigned by nothing and named by nothing, and a temporary that only exists
/// inside a block nobody reaches would be an unused variable.
fn assigned(function: &Function, live: &[bool], value: u32) -> bool {
    for (index, block) in function.blocks.iter().enumerate() {
        if !live[index] {
            continue;
        }
        for one in &block.insts {
            if one.dest == Some(crate::ir::ValueId(value)) {
                return true;
            }
        }
    }
    false
}
