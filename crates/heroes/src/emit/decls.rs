//! One translation unit's skeleton: prototypes, prologues, the shim (design.md
//! §3.1, panel 020).
//!
//! **Declaration ordering** is the first of the emitter's two obligations. Heroes'
//! top level is order-free and mutual recursion needs no forward declarations
//! (§4.2); C's does not work that way. So every prototype is emitted before every
//! definition, in source order — deterministic, and it needs no topological sort at
//! M5a because there are no `typedef struct`s yet: aggregates arrive with the
//! descriptor pass at M5c, and their containment cycles with them.
//!
//! **The prologue exists because `goto` may not jump over an initialisation.**
//! Every slot and every temporary is declared at the top of the function, and
//! nothing is given an initial value: a Heroes binding is always initialised
//! (§4.4) and a synthetic join slot is written on every arm, so a C local that
//! clang thinks may be read uninitialised is a *lowering* bug — which is exactly
//! what `-Werror=uninitialized` is in the flag set to catch. Zero-initialising them
//! would hide it.
//!
//! **The `main` shim, not a mangler exception.** Heroes' `main` becomes
//! `h_<module>_main` like every other function, and a separate `int main(void)`
//! calls it. Vala does exactly this (`ccode.add_return (main_call)`), Nim's
//! generated `main` is a shim and `NimMain()` is where initialisation goes, and
//! Zig's C backend once emitted `void main(void)` — which clang rejects. The shim
//! is also where runtime setup will go when there is any.

use crate::ir::{is_refcounted, Function, Program, SlotId, SlotKind};
use crate::source::Source;
use crate::syntax::Ast;
use crate::types::Checked;

use super::ctype::{c_result, c_type, is_unit, Names};
use super::mangle;
